CREATE TABLE IF NOT EXISTS pokemon_catalog.max_battle_tiers (
  tier_key TEXT PRIMARY KEY,
  label TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('standard', 'legendary', 'gigantamax')),
  boss_hp INTEGER NOT NULL CHECK (boss_hp > 0),
  default_trainers INTEGER NOT NULL CHECK (default_trainers > 0),
  max_trainers INTEGER NOT NULL CHECK (max_trainers >= default_trainers),
  battle_seconds INTEGER NOT NULL DEFAULT 360 CHECK (battle_seconds > 0),
  enrage_seconds INTEGER NOT NULL DEFAULT 360 CHECK (enrage_seconds > 0),
  subgroup_size INTEGER NOT NULL DEFAULT 4 CHECK (subgroup_size > 0),
  meter_orb_energy INTEGER NOT NULL DEFAULT 10 CHECK (meter_orb_energy >= 0)
);

