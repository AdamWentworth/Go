CREATE TABLE IF NOT EXISTS pokemon_catalog.max_battle_profiles (
  profile_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pokemon_id INTEGER NOT NULL REFERENCES pokemon_catalog.pokemon(pokemon_id) ON DELETE CASCADE,
  variant_kind TEXT NOT NULL CHECK (variant_kind IN ('dynamax', 'gigantamax', 'special')),
  form TEXT,
  tier_key TEXT NOT NULL REFERENCES pokemon_catalog.max_battle_tiers(tier_key),
  label_override TEXT,
  boss_hp_override INTEGER CHECK (boss_hp_override IS NULL OR boss_hp_override > 0),
  default_trainers_override INTEGER CHECK (
    default_trainers_override IS NULL OR default_trainers_override > 0
  ),
  max_trainers_override INTEGER CHECK (
    max_trainers_override IS NULL OR max_trainers_override > 0
  ),
  battle_seconds_override INTEGER CHECK (
    battle_seconds_override IS NULL OR battle_seconds_override > 0
  ),
  enrage_seconds_override INTEGER CHECK (
    enrage_seconds_override IS NULL OR enrage_seconds_override > 0
  ),
  starts_at TIMESTAMPTZ,
  ends_at TIMESTAMPTZ,
  is_default BOOLEAN NOT NULL DEFAULT FALSE,
  priority INTEGER NOT NULL DEFAULT 0,
  source_name TEXT,
  source_url TEXT,
  notes TEXT,
  CHECK (ends_at IS NULL OR starts_at IS NULL OR ends_at > starts_at),
  CHECK (
    max_trainers_override IS NULL
    OR default_trainers_override IS NULL
    OR max_trainers_override >= default_trainers_override
  )
);

CREATE INDEX IF NOT EXISTS idx_max_battle_profiles_pokemon_id
  ON pokemon_catalog.max_battle_profiles(pokemon_id);

CREATE INDEX IF NOT EXISTS idx_max_battle_profiles_active_window
  ON pokemon_catalog.max_battle_profiles(starts_at, ends_at)
  WHERE starts_at IS NOT NULL OR ends_at IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS max_battle_profiles_one_default
  ON pokemon_catalog.max_battle_profiles (
    pokemon_id,
    variant_kind,
    COALESCE(LOWER(form), '')
  )
  WHERE is_default IS TRUE;

CREATE UNIQUE INDEX IF NOT EXISTS max_battle_profiles_unique_entry
  ON pokemon_catalog.max_battle_profiles (
    pokemon_id,
    variant_kind,
    COALESCE(LOWER(form), ''),
    tier_key,
    COALESCE(starts_at, '-infinity'::TIMESTAMPTZ),
    COALESCE(ends_at, 'infinity'::TIMESTAMPTZ)
  );

